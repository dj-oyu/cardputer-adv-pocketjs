static __attribute__((noinline)) void vec_exec(ksn_shiki_vm *vm,const ksn_shiki_plan *plan,const ksn_shiki_inst *i){
    vlanes *v=vregs(vm);
    int64_t *acc=ksn_shiki_vm_acc(vm);
    const int32_t *r=vm->reg;
    const unsigned lv=i->level;
    /* rel: the block's first lane from the loop's start; base: its record. */
    const uint32_t rel=(uint32_t)(vm->loop[lv].total-vm->loop[lv].remaining)*8u;
    const uint32_t base=vm->loop[lv].start+rel;
    const uint32_t n=vm->loop[lv].n;
    const unsigned live=n-rel>=8?8u:(unsigned)(n-rel);
#if KSN_SHIKI_HAS_PIE
    if(vm->pie){
        switch(i->op){
        case KSN_SHIKI_VLOAD: {
            const ksn_shiki_bound *g=&plan->region[i->a];
            const int16_t *d=(const int16_t *)g->data+(uint32_t)i->b*g->stride+base;
            if(live==8&&!((uintptr_t)d&15u)){pie_copy(v[i->dst],d);return;}
            break;                                   /* the C model's lane loop */
        }
        case KSN_SHIKI_VSTORE: {
            const ksn_shiki_bound *g=&plan->region[i->a];
            int16_t *d=(int16_t *)g->data+(uint32_t)i->b*g->stride+base;
            if(live==8&&!((uintptr_t)d&15u)){pie_copy(d,v[i->dst]);return;}
            break;
        }
        case KSN_SHIKI_VSPLAT: {
            const int16_t k=(int16_t)sat16(r[i->a]);
            pie_splat(v[i->dst],&k);
            return;
        }
        case KSN_SHIKI_VADD: pie_vadd(v[i->dst],v[i->a],v[i->b]); return;
        case KSN_SHIKI_VSUB: pie_vsub(v[i->dst],v[i->a],v[i->b]); return;
        case KSN_SHIKI_VMIN: pie_vmin(v[i->dst],v[i->a],v[i->b]); return;
        case KSN_SHIKI_VMAX: pie_vmax(v[i->dst],v[i->a],v[i->b]); return;
        /* The accumulator is QACC's image here: every use goes to PIE. */
        case KSN_SHIKI_VZACC: pie_zacc(acc); return;
        case KSN_SHIKI_VMAC: pie_mac(acc,v[i->a],v[i->b]); return;
        case KSN_SHIKI_VMACK: {
            const int16_t k=(int16_t)sat16(r[i->b]);
            pie_mack(acc,v[i->a],&k);
            return;
        }
        case KSN_SHIKI_VACCSET: pie_accset(acc,r[i->a]); return;
        case KSN_SHIKI_VOUT: pie_out(acc,v[i->dst],i->aux); return;
        default: break;                              /* VIOTA */
        }
    }
#endif
    switch(i->op){
    case KSN_SHIKI_VLOAD: {
        const ksn_shiki_bound *g=&plan->region[i->a];
        const int16_t *d=(const int16_t *)g->data+(uint32_t)i->b*g->stride+base;
        for(unsigned l=0;l<8;l++)v[i->dst][l]=l<live?d[l]:0;
        break;
    }
    case KSN_SHIKI_VSTORE: {
        const ksn_shiki_bound *g=&plan->region[i->a];
        int16_t *d=(int16_t *)g->data+(uint32_t)i->b*g->stride+base;
        for(unsigned l=0;l<live;l++)d[l]=v[i->dst][l];
        break;
    }
    case KSN_SHIKI_VSPLAT: {
        const int16_t x=(int16_t)sat16(r[i->a]);
        for(unsigned l=0;l<8;l++)v[i->dst][l]=x;
        break;
    }
    case KSN_SHIKI_VIOTA:
        for(unsigned l=0;l<8;l++)v[i->dst][l]=(int16_t)sat16((int64_t)base+l);
        break;
    case KSN_SHIKI_VADD:
        for(unsigned l=0;l<8;l++)v[i->dst][l]=(int16_t)sat16((int32_t)v[i->a][l]+v[i->b][l]);
        break;
    case KSN_SHIKI_VSUB:
        for(unsigned l=0;l<8;l++)v[i->dst][l]=(int16_t)sat16((int32_t)v[i->a][l]-v[i->b][l]);
        break;
    case KSN_SHIKI_VMIN:
        for(unsigned l=0;l<8;l++)v[i->dst][l]=v[i->a][l]<v[i->b][l]?v[i->a][l]:v[i->b][l];
        break;
    case KSN_SHIKI_VMAX:
        for(unsigned l=0;l<8;l++)v[i->dst][l]=v[i->a][l]>v[i->b][l]?v[i->a][l]:v[i->b][l];
        break;
    case KSN_SHIKI_VZACC:
        for(unsigned l=0;l<8;l++)acc[l]=0;
        break;
    case KSN_SHIKI_VMAC:
        for(unsigned l=0;l<8;l++)acc[l]=sat40(acc[l]+(int32_t)v[i->a][l]*v[i->b][l]);
        break;
    case KSN_SHIKI_VMACK: {
        const int32_t k=sat16(r[i->b]);
        for(unsigned l=0;l<8;l++)acc[l]=sat40(acc[l]+(int32_t)v[i->a][l]*k);
        break;
    }
    case KSN_SHIKI_VACCSET:
        for(unsigned l=0;l<8;l++)acc[l]=r[i->a];
        break;
    case KSN_SHIKI_VOUT:
        for(unsigned l=0;l<8;l++){
            acc[l]=floor_shift(acc[l],i->aux);
            v[i->dst][l]=(int16_t)sat16(acc[l]);
        }
        break;
    default: break;
    }
}
/* EMIT_POINTS / EMIT_LINES: the records from the start (dst bit 1: r[b],
 * else 0) to the end, or the count of them (dst bit 0), of an i16 region
 * as points (x, y) or lines (x0, y0, x1, y1) at Q imm, each coordinate to
 * the nearest pixel (halves up), outside -480..720 INVALID. The pen is not
 * touched. */
static __attribute__((noinline)) ksn_shiki_status emit_exec(ksn_shiki_vm *vm,const ksn_shiki_plan *plan,
                                                            ksn_proc_segment *out,const ksn_shiki_inst *i){
    const ksn_shiki_bound *g=&plan->region[i->a];
    uint32_t start=0;
    if(i->dst&2){
        const int32_t s=vm->reg[i->b];
        if(s<0||(uint32_t)s>g->records)return KSN_SHIKI_INVALID;
        start=(uint32_t)s;
    }
    uint32_t count=g->records-start;
    if(i->dst&1){
        const int32_t c=vm->reg[i->dst&2?i->b+1u:i->b];
        if(c<0||(uint32_t)c>g->records-start)return KSN_SHIKI_INVALID;
        count=(uint32_t)c;
    }
    const unsigned q=(unsigned)i->imm;
    const int32_t half=q?1<<(q-1):0;
    const bool lines=i->op==KSN_SHIKI_EMIT_LINES;
    const int16_t *d=(const int16_t *)g->data+start;
    /* A record's fields are a plane apart (sec.5.1). */
    const uint32_t field=g->stride;
    const uint16_t colour=i->aux;
    /* The same results as one emit() per record (a record's coordinates
     * checked before it is emitted, INVALID or LIMIT at the first record
     * that fails, the records before it kept), in a loop with no call and
     * 32-bit arithmetic: the raw value is an int16 and half < 2^15. */
    if(!lines){
        /* A point costs 1 raster step and 1 segment, so how many fit is
         * known before the loop. */
        uint32_t room=vm->count<vm->cap?(uint32_t)vm->cap-vm->count:0u;
        if(KSN_SHIKI_RASTER-(uint32_t)vm->raster<room)room=KSN_SHIKI_RASTER-(uint32_t)vm->raster;
        const uint32_t n=count<room?count:room;
        const int16_t *xs=d,*ys=d+field;
        ksn_proc_segment *o=out+vm->count;
        uint32_t c=0;
        for(;c<n;c++){
            const int32_t x=floor_shr32(xs[c]+half,q),y=floor_shr32(ys[c]+half,q);
            if((uint32_t)(x+480)>1200u||(uint32_t)(y+480)>1200u)break;
            o[c]=(ksn_proc_segment){(int16_t)x,(int16_t)y,(int16_t)x,(int16_t)y,colour};
        }
        vm->count=(uint16_t)(vm->count+c);
        vm->raster=(uint16_t)(vm->raster+c);
        if(c<n)return KSN_SHIKI_INVALID;
        if(n==count)return KSN_SHIKI_RUNNING;
        /* Out of room at record n: its coordinates are still checked first. */
        const int32_t x=floor_shr32(xs[n]+half,q),y=floor_shr32(ys[n]+half,q);
        return (uint32_t)(x+480)>1200u||(uint32_t)(y+480)>1200u?KSN_SHIKI_INVALID:KSN_SHIKI_LIMIT;
    }
    for(uint32_t c=0;c<count;c++,d++){
        int32_t p[4];
        for(unsigned j=0;j<4u;j++){
            p[j]=floor_shr32(d[j*field]+half,q);
            if((uint32_t)(p[j]+480)>1200u)return KSN_SHIKI_INVALID;
        }
        if(vm->count>=vm->cap)return KSN_SHIKI_LIMIT;
        const int32_t dx=p[2]>p[0]?p[2]-p[0]:p[0]-p[2],dy=p[3]>p[1]?p[3]-p[1]:p[1]-p[3];
        const uint32_t cost=(uint32_t)(dx>dy?dx:dy)+1u;
        if(vm->raster+cost>KSN_SHIKI_RASTER)return KSN_SHIKI_LIMIT;
        vm->raster=(uint16_t)(vm->raster+cost);
        out[vm->count++]=(ksn_proc_segment){(int16_t)p[0],(int16_t)p[1],(int16_t)p[2],(int16_t)p[3],colour};
    }
    return KSN_SHIKI_RUNNING;
}

ksn_shiki_status ksn_shiki_draw(const ksn_shiki_plan *plan,const double *inputs,unsigned n,
                                ksn_shiki_vm *vm,ksn_proc_segment out[KSN_SHIKI_SEGMENTS]){
    int32_t in[KSN_SHIKI_INPUTS]={0};
    for(unsigned k=0;k<plan->inputs;k++)
        if(!ksn_shiki_from_double(k<n?inputs[k]:0.0,plan->input_q[k],&in[k])){
            memset(vm,0,sizeof *vm);
            return KSN_SHIKI_BADINPUT;
        }
    return ksn_shiki_draw_fixed(plan,in,plan->inputs,vm,out);
}

