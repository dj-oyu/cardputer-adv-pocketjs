"""Bind verification artifacts to the actual checked-out source, never a label."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import struct
import subprocess
from derby_telemetry_chunks import instrument

ROOT = Path(__file__).resolve().parents[1]
TELEMETRY_SYMBOLS = {
    'derby_telemetry_reset', 'derby_telemetry_begin_frame', 'derby_telemetry_set',
    'derby_telemetry_eval', 'derby_telemetry_io_us', 'derby_telemetry_present',
    'derby_telemetry_write',
}

MEASURE_SYMBOLS = {
    'dm_now_us', 'dm_enter', 'dm_leave', 'dm_reset', 'dm_read', 'dm_heap',
    'dm_batch', 'dm_calibrate', 'dm_dispatch', 'dm_present', 'dm_transfer',
    'dm_output_reset', 'dm_refused', 'dm_format_record', 'dm_emit',
}



FIXED_SYMBOLS = {'df_fixture_id','df_fixture_manifest','df_now_us','df_write','df_variant',
    'df_reset','df_session','df_measuring','df_status','df_command','df_dispatch','df_present',
    'df_owner_begin','df_owner_work_end','df_pace_begin','df_pace_end','df_owner_end','df_count','df_fail'}

# Pure same-TU helpers can be inlined and removed by section GC. Boundary APIs cannot.
FIXED_REQUIRED=FIXED_SYMBOLS-{'df_measuring','df_fail'}
DETAIL_FIXED_SYMBOLS={'df_detail_exit_record'}

def fixed_mode(build):
    values=[line.split('=',1)[1] for line in (build/'CMakeCache.txt').read_text().splitlines()
            if line.startswith('POCKET_DERBY_FIXED_WORKLOAD:BOOL=')]
    if not values:return 'OFF'  # archived proof fixtures before the option existed
    if len(values)!=1 or values[0] not in ('ON','OFF'):raise ValueError('ambiguous fixed workload mode')
    return values[0]

def detail_mode(build):
    values=[line.split('=',1)[1].upper() for line in (build/'CMakeCache.txt').read_text().splitlines()
            if line.startswith('POCKET_DERBY_DETAIL_MEASURE:BOOL=')]
    if not values:return 'OFF'
    if len(values)!=1 or values[0] not in ('ON','OFF','TRUE','FALSE','YES','NO','1','0'):
        raise ValueError('ambiguous detail mode')
    return 'ON' if values[0] in ('ON','TRUE','YES','1') else 'OFF'

DETAIL_REQUIRED={'dd_start','dd_finish','dd_enter','dd_leave','dd_add','dd_js','dd_suspend','dd_resume'}
def verify_detail_mode(build):
    mode=detail_mode(build);symbols={s for s in elf_symbols(build) if s.startswith('dd_')}
    if mode=='OFF':
        if symbols:raise ValueError('OFF detail symbols present')
    elif fixed_mode(build)!='ON' or not DETAIL_REQUIRED<=symbols:
        raise ValueError('ON detail requires fixed workload and detail boundary symbols')
    return dict(mode=mode,native_symbols=sorted(symbols))

def fixed_expected(detail=False):
    import tempfile
    from derby_fixed_workload_chunks import generate
    with tempfile.TemporaryDirectory() as tmp:
        out=Path(tmp);generate(ROOT/'apps/derby',out,detail)
        return {name:(out/name).read_bytes() for name in ('derby_watch.js','derby_view.js','derby_play.js','derby_fixed.js')}

def verify_fixed_mode(build):
    from derby_fixed_workload_chunks import FIXTURE,MANIFEST_SHA256
    mode=fixed_mode(build);symbols={s for s in elf_symbols(build) if s.startswith('df_')}
    elf=(build/'cardputer_pocketjs.elf').read_bytes()
    if mode=='OFF':
        if symbols or b'DF fixture oval-pan8-390-510-v1' in elf:
            raise ValueError('OFF fixed workload must compile out code and fixture bytes')
        return dict(mode=mode,native_symbols=[])
    detail=detail_mode(build)=='ON'
    extra=DETAIL_FIXED_SYMBOLS if detail else set()
    required=FIXED_REQUIRED|extra;allowed=FIXED_SYMBOLS|extra
    if not required<=symbols or not symbols<=allowed:
        raise ValueError('fixed workload ELF boundary symbols differ')
    for name,expected in fixed_expected(detail).items():
        path=build/'generated/derby_fixed_workload'/name
        source_path=ROOT/'apps/derby'/name
        source=source_path.read_bytes() if source_path.exists() else None
        if (not path.is_file() or path.read_bytes()!=expected or expected+b'\0' not in elf
                or source is not None and source+b'\0' in elf):
            raise ValueError('fixed workload exact generated bytes required: '+name)
    if detail:
        from derby_detail_chunks import instrument as detail_instrument
        pan=detail_instrument('pan',(ROOT/'apps/derby/derby_pan.js').read_text())
        batch=any(line.upper()=='POCKET_DERBY_RUNNER_BATCH:BOOL=ON' for line in (build/'CMakeCache.txt').read_text().splitlines())
        folder='derby_fixed_workload'
        if batch:
            from games.derby_runner_batch import instrument as batch_instrument
            pan=batch_instrument(pan);folder='derby_runner_batch'
        path=build/'generated'/folder/'derby_pan.js'
        if not path.is_file() or path.read_bytes()!=pan.encode() or pan.encode()+b'\0' not in elf:
            raise ValueError('detail PAN exact embedded bytes required')
    if MANIFEST_SHA256.encode()+b'\0' not in elf:raise ValueError('fixed workload manifest missing in ELF')
    return dict(mode=mode,native_symbols=sorted(symbols),fixture=FIXTURE,manifest_sha256=MANIFEST_SHA256)


def verify_measure_mode(build, expected=None):
    cache = (build/'CMakeCache.txt').read_bytes()
    values = [line.split('=', 1)[1] for line in cache.decode().splitlines()
              if line.startswith('POCKET_DERBY_MEASURE:BOOL=')]
    if len(values)!=1 or values[0] not in ('ON','OFF'):
        raise ValueError('missing or ambiguous measure CMake setting')
    mode = values[0]
    if expected is not None and mode!=expected:
        raise ValueError('measure mode differs from requested artifact mode')
    symbols = {s for s in elf_symbols(build) if s.startswith('dm_')}
    if (mode=='OFF' and symbols) or (mode=='ON' and symbols!=MEASURE_SYMBOLS):
        raise ValueError('measure ELF symbols do not match the actual CMake mode')
    return dict(measure_mode=mode, native_symbols=sorted(symbols),
                cmake_cache_sha256=hashlib.sha256(cache).hexdigest())


def elf_symbols(build):
    text = command('xtensa-esp32s3-elf-nm', '--defined-only', str(build/'cardputer_pocketjs.elf'))
    return {line.rsplit(None, 1)[-1] for line in text.splitlines() if line.strip()}


def verify_mode(build, expected=None):
    cache = (build/'CMakeCache.txt').read_bytes()
    values = [line.split('=', 1)[1] for line in cache.decode().splitlines()
              if line.startswith('POCKET_DERBY_TELEMETRY:BOOL=')]
    if len(values)!=1 or values[0] not in ('ON','OFF'):
        raise ValueError('missing or ambiguous telemetry CMake setting')
    mode = values[0]
    if expected is not None and mode!=expected:
        raise ValueError('telemetry mode differs from requested artifact mode')
    symbols = {s for s in elf_symbols(build) if s.startswith('derby_telemetry_')}
    source = (ROOT/'apps/derby/derby_play.js').read_bytes()
    generated = instrument(source.decode()).encode()
    path = build/'generated/derby_telemetry/derby_play.js'
    if fixed_mode(build)=='ON':
        generated=fixed_expected(detail_mode(build)=='ON')['derby_play.js']
        path=build/'generated/derby_fixed_workload/derby_play.js'
    elf = (build/'cardputer_pocketjs.elf').read_bytes()
    if mode=='ON':
        if symbols!=TELEMETRY_SYMBOLS or not path.is_file() or path.read_bytes()!=generated:
            raise ValueError('ON requires expected native symbols and exact generated chunk')
        if generated+b'\0' not in elf or source+b'\0' in elf:
            raise ValueError('ON ELF does not embed only the generated play chunk')
        embedded=generated
    else:
        if symbols or path.exists() or generated+b'\0' in elf or source+b'\0' not in elf:
            raise ValueError('OFF must omit telemetry symbols/generated chunk and embed shipping play')
        embedded=source
    return dict(telemetry_mode=mode, cmake_cache_sha256=hashlib.sha256(cache).hexdigest(),
                native_symbols=sorted(symbols), generated_chunk_present=mode=='ON',
                embedded_play_bytes=len(embedded), embedded_play_sha256=hashlib.sha256(embedded).hexdigest(),
                source_play_sha256=hashlib.sha256(source).hexdigest(), elf_embedded_play_verified=True)


def command(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def verify_build(build, head):
    description = json.loads((build / "project_description.json").read_text())
    if (Path(description["project_path"]).resolve() != ROOT.resolve()
            or description["project_version"] != head[:12]):
        raise ValueError("build source/version does not match the exact verification head")
    image = (build / "cardputer_pocketjs.bin").read_bytes()
    # ESP32-S3 app image: 24-byte image header, 8-byte first segment header,
    # then IDF 6.0.1's esp_app_desc_t. Validate its magic before reading fields.
    if len(image) < 288 or image[0] != 0xE9 or struct.unpack_from("<I", image, 32)[0] != 0xABCD5432:
        raise ValueError("invalid application descriptor")
    if image[48:80].split(b"\0")[0] != head[:12].encode():
        raise ValueError("BIN contains another source version")
    if image[144:176].split(b"\0")[0] != b"v6.0.1":
        raise ValueError("ESP-IDF 6.0.1 required in the actual BIN")
    elf_hash = hashlib.sha256((build / "cardputer_pocketjs.elf").read_bytes()).digest()
    if image[176:208] != elf_hash:
        raise ValueError("BIN and ELF do not belong to the same build")
    return description, elf_hash.hex()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--expect-telemetry", choices=('ON','OFF'))
    parser.add_argument("--expect-measure", choices=("ON","OFF"))
    args = parser.parse_args()
    head = command("git", "rev-parse", "HEAD")
    expected = os.environ.get("SOURCE_HEAD", head)
    if head != expected or command("git", "status", "--porcelain", "--untracked-files=no"):
        raise SystemExit("verification requires the exact clean source head")
    report = dict(source_commit=head, source_tree=command("git", "rev-parse", "HEAD^{tree}"),
                  python=platform.python_version(), node=command("node", "--version"),
                  hardware_tested=False)
    report["submodule_gitlinks"] = command("git", "ls-tree", "HEAD", "third_party/")
    if args.build:
        build = args.build.resolve()
        description, elf_hash = verify_build(build, head)
        report['build_mode'] = verify_mode(build, args.expect_telemetry)
        report['build_measure'] = verify_measure_mode(build, args.expect_measure)
        report['fixed_workload'] = verify_fixed_mode(build)
        report['detail_measurement'] = verify_detail_mode(build)
        report["idf_version"] = "v6.0.1"
        report["embedded_elf_sha256"] = elf_hash
        report["project_version"] = description["project_version"]
        names = ["cardputer_pocketjs.bin", "cardputer_pocketjs.elf", "cardputer_pocketjs.map",
                 "sdkconfig", "project_description.json", "bootloader/bootloader.bin",
                 "partition_table/partition-table.bin"]
        report["artifacts"] = {name: dict(bytes=(build / name).stat().st_size,
            sha256=hashlib.sha256((build / name).read_bytes()).hexdigest()) for name in names}
        (build / "SHA256SUMS").write_text("".join(
            f"{item['sha256']}  {name}\n" for name, item in report["artifacts"].items()))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
