"""Generate the firmware RGB565 LCD test chart and a matching PNG preview."""

import argparse
from pathlib import Path
import struct
import zlib


WIDTH, HEIGHT = 240, 135


def chart_pixel(x, y):
    if x in (0, WIDTH - 1) or y in (0, HEIGHT - 1):
        return (202, 213, 217)
    if y >= 120:
        if x < 96:
            return ((168, 52, 76), (55, 140, 91), (57, 105, 176),
                    (69, 159, 164), (168, 135, 68), (149, 89, 145))[x // 16]
        level = 20 + (x - 96) * 225 // (WIDTH - 97)
        return (level, level, level)
    if x < 60:
        if 7 <= y < 24:
            return (188, 203, 212) if (x + y) % 4 < 2 else (31, 46, 61)
        if 32 <= y < 55:
            return (163, 179, 198) if (x // 4 + y // 4) % 2 else (46, 60, 76)
        if 63 <= y < 113:
            return (177, 197, 202) if (x - y) % 12 < 2 else (32, 48, 63)
    if x % 24 == 0 or y % 15 == 0:
        return (51, 69, 81)
    if (x + 2 * y) % 40 == 0:
        return (43, 61, 73)
    return (23, 34, 47) if (x // 24 + y // 15) % 2 else (29, 41, 55)


def rgb565(rgb):
    red, green, blue = rgb
    return (red >> 3) << 11 | (green >> 2) << 5 | blue >> 3


def png_chunk(kind, data):
    return (struct.pack(">I", len(data)) + kind + data
            + struct.pack(">I", zlib.crc32(kind + data)))


def write_png(path, words):
    def expand(value, bits):
        return value * 255 // ((1 << bits) - 1)

    data = bytearray()
    for y in range(HEIGHT):
        data.append(0)
        for word in words[y * WIDTH:(y + 1) * WIDTH]:
            data.extend((expand(word >> 11, 5), expand((word >> 5) & 63, 6),
                         expand(word & 31, 5)))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 2, 0, 0, 0))
        + png_chunk(b"IDAT", zlib.compress(data))
        + png_chunk(b"IEND", b"")
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    words = [rgb565(chart_pixel(x, y)) for y in range(HEIGHT) for x in range(WIDTH)]
    args.header.parent.mkdir(parents=True, exist_ok=True)
    with args.header.open("w", encoding="ascii", newline="\n") as header:
        header.write("/* Generated by tools/hone/make_companion_raster_test.py. */\n"
                     "#pragma once\n#include <stdint.h>\n"
                     f"#define AY_RASTER_WIDTH {WIDTH}\n#define AY_RASTER_HEIGHT {HEIGHT}\n"
                     "static const uint16_t ay_raster_pixels[AY_RASTER_WIDTH * AY_RASTER_HEIGHT] = {\n")
        for row in range(0, len(words), 12):
            header.write("    " + ", ".join(f"0x{word:04x}" for word in words[row:row + 12]) + ",\n")
        header.write("};\n")
    if args.preview:
        write_png(args.preview, words)


if __name__ == "__main__":
    main()
