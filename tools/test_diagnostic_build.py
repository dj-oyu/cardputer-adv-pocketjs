"""The archive-safe proof rejects a mixed or unsupported image pair."""
import hashlib
from pathlib import Path
import struct
import tempfile
import unittest
from unittest.mock import patch

from verify_diagnostic_build import prove
from derby_compare_chunks import instrument as compare_view
from derby_fixed_workload_chunks import generate, MANIFEST_SHA256
from record_verification import FIXED_SYMBOLS


class DiagnosticProofTests(unittest.TestCase):
    def test_actual_pair_and_sdk_required_without_git(self):
        with tempfile.TemporaryDirectory() as temp:
            build = Path(temp)
            source_view = (Path(__file__).resolve().parents[1]/'apps/derby/derby_view.js').read_bytes()
            fixture = build/'generated/derby_fixed_workload'
            generate(Path(__file__).resolve().parents[1]/'apps/derby', fixture)
            generated_path = fixture/'derby_view.js'
            generated_view = generated_path.read_bytes()
            elf = b'example ELF' + b'\0'.join((fixture/name).read_bytes() for name in
                ('derby_watch.js','derby_view.js','derby_play.js','derby_fixed.js')) + b'\0' + MANIFEST_SHA256.encode() + b'\0'
            (build/'cardputer_pocketjs.elf').write_bytes(elf)
            image = bytearray(288)
            image[0] = 0xE9
            struct.pack_into('<I', image, 32, 0xABCD5432)
            image[144:150] = b'v6.0.1'
            image[176:208] = hashlib.sha256(elf).digest()
            path = build/'cardputer_pocketjs.bin'
            path.write_bytes(image)
            cache = build/'CMakeCache.txt'
            fixed_on = 'POCKET_DERBY_FIXED_WORKLOAD:BOOL=ON\n'
            cache.write_text(fixed_on+'POCKET_DERBY_COMPARE_FIXED_HW:BOOL=ON\n')
            with patch('verify_diagnostic_build.verify_mode', return_value={'telemetry_mode':'ON'}) as mode, \
                 patch('verify_diagnostic_build.verify_measure_mode', return_value={'measure_mode':'ON'}) as measure, \
                 patch('record_verification.elf_symbols', return_value=FIXED_SYMBOLS), \
                 patch('verify_diagnostic_build.symbol_u32', return_value=0x2545F491) as seed:
                self.assertEqual(prove(build)['artifacts']['cardputer_pocketjs.bin']['sha256'], hashlib.sha256(image).hexdigest())
                mode.assert_called_once_with(build, 'ON')
                measure.assert_called_once_with(build, 'ON')
                seed.assert_called_with(elf, 'pocket_derby_comparison_hw_seed')
                self.assertEqual(prove(build)['build_measure']['measure_mode'],'ON')
                self.assertEqual(prove(build)['comparison_seed']['hardware_seed'],'2545F491')
                self.assertEqual(prove(build)['comparison_seed']['saved_race'],19)
                self.assertEqual(prove(build)['fixed_workload']['mode'],'ON')
                self.assertEqual(prove(build)['fixed_workload']['manifest_sha256'],MANIFEST_SHA256)
                # An otherwise paired legacy measurement image must not qualify
                # this finite diagnostic source when the mode is OFF or absent.
                legacy_view = compare_view(source_view.decode()).encode()
                legacy_path = build/'generated/derby_telemetry/derby_view.js'
                legacy_path.parent.mkdir(parents=True);legacy_path.write_bytes(legacy_view)
                legacy_elf = b'legacy measurement ELF'+legacy_view+b'\0'
                (build/'cardputer_pocketjs.elf').write_bytes(legacy_elf)
                legacy_image = image.copy();legacy_image[176:208] = hashlib.sha256(legacy_elf).digest()
                path.write_bytes(legacy_image)
                for setting in ('POCKET_DERBY_FIXED_WORKLOAD:BOOL=OFF\n',''):
                    cache.write_text(setting+'POCKET_DERBY_COMPARE_FIXED_HW:BOOL=ON\n')
                    with self.subTest(setting=setting), patch('record_verification.elf_symbols',return_value=set()):
                        with self.assertRaisesRegex(ValueError,'requires fixed workload ON'):
                            prove(build)
                cache.write_text(fixed_on+'POCKET_DERBY_COMPARE_FIXED_HW:BOOL=ON\n')
                with patch('record_verification.elf_symbols',return_value=set()), self.assertRaises(ValueError):
                    prove(build)
                # A claimed ON cache/symbol set cannot launder ordinary bytes.
                with self.assertRaisesRegex(ValueError,'exact generated bytes required'):
                    prove(build)
                (build/'cardputer_pocketjs.elf').write_bytes(elf);path.write_bytes(image)
                with patch('verify_diagnostic_build.symbol_u32', return_value=0x2545F490), self.assertRaises(ValueError):
                    prove(build)
                generated_path.write_bytes(b'wrong generated view')
                with self.assertRaises(ValueError):
                    prove(build)
                generated_path.write_bytes(generated_view)
                (build/'cardputer_pocketjs.elf').write_bytes(b'example ELF' + source_view + b'\0')
                with self.assertRaises(ValueError):
                    prove(build)
                (build/'cardputer_pocketjs.elf').write_bytes(elf)
                cache.write_text(fixed_on+'POCKET_DERBY_COMPARE_FIXED_HW:BOOL=OFF\n')
                with self.assertRaises(ValueError):
                    prove(build)
                cache.write_text(fixed_on+'POCKET_DERBY_COMPARE_FIXED_HW:BOOL=ON\n')
                for offset in (0, 32, 144, 176):
                    changed = image.copy()
                    changed[offset] ^= 1
                    path.write_bytes(changed)
                    with self.subTest(offset=offset), self.assertRaises(ValueError):
                        prove(build)
                path.write_bytes(image)
                (build/'cardputer_pocketjs.elf').write_bytes(b'another ELF prefix'+elf)
                with self.assertRaises(ValueError):
                    prove(build)


if __name__ == '__main__':
    unittest.main()
