#!/usr/bin/env python3
"""Writes main/hal/fetch_probe_blocks.S: the code the instruction-fetch probe
(main/hal/fetch_probe.c) times from IRAM, RTC fast memory and flash.

Two shapes per memory:
  seq    SEQ_INSNS straight-line `add`s (sequential fetch, no taken branch)
  chain  CHAIN_LINES blocks of 8 `add`s + `j`, each aligned to 32 B (one cache
         line), visited once each in a fixed pseudo-random order, so every
         line is a separate miss and the next line cannot be prefetched
Regenerate with: python tools/gen_fetch_probe.py > main/hal/fetch_probe_blocks.S
"""
import random

SEQ_INSNS = 512      # 1,536 B
CHAIN_LINES = 48     # 1,536 B
MEMS = [("iram", '.section .iram1.fetchprobe,"ax"'),
        ("rtc", '.section .rtc.text.fetchprobe,"ax"'),
        ("flash", '.section .text.fetchprobe,"ax"')]

random.seed(116)
order = list(range(1, CHAIN_LINES))
random.shuffle(order)
order = [0] + order          # a single cycle through every line, starting at 0

print("/* Generated by tools/gen_fetch_probe.py -- do not edit. */")
print('#include "sdkconfig.h"')
print("#if CONFIG_POCKET_FETCH_PROBE")
for mem, sec in MEMS:
    print(f"\n{sec}")
    print(".balign 32")
    print(f".global fp_seq_{mem}\n.type fp_seq_{mem},@function\nfp_seq_{mem}:")
    print("    entry a1, 16")
    for _ in range(SEQ_INSNS):
        print("    add a4, a4, a5")
    print("    retw.n")
    print(f".size fp_seq_{mem}, .-fp_seq_{mem}")
    print(".balign 32")
    print(f".global fp_chain_{mem}\n.type fp_chain_{mem},@function\nfp_chain_{mem}:")
    print(f"    entry a1, 16\n    j .Lfp_{mem}_{order[0]}")
    print(".balign 32")
    for k, b in enumerate(order):
        print(f".Lfp_{mem}_{b}:")
        for _ in range(8):
            print("    add a4, a4, a5")
        nxt = f".Lfp_{mem}_{order[k+1]}" if k + 1 < len(order) else f".Lfp_{mem}_exit"
        print(f"    j {nxt}")
        print(".balign 32")
    print(f".Lfp_{mem}_exit:\n    retw.n")
    print(f".size fp_chain_{mem}, .-fp_chain_{mem}")
print("\n#endif")
