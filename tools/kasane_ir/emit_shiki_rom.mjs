// The firmware's built-in Shiki programs: an app's @shiki functions compiled
// (shiki_compile.mjs, spec sec.8) to const C, so that
// pocket.kasane.shiki.register('APP.name', args) finds them in flash and the
// guest neither holds their bytes nor evaluates their source (lower_plans.mjs
// --rom removes the functions from the shipped chunk). Host only (Node 16+).
//
//   node tools/kasane_ir/emit_shiki_rom.mjs OUT.c APP=FILE.js [APP=FILE.js ...]
//
// OUT.c defines ksn_shiki_rom_table() over a static table, overriding the
// weak empty one in main/pocket/pocket_shiki_api.c. Names are 'APP.name' and unique; a function
// the compiler refuses stops the build with its message.
import fs from 'node:fs';
import {findPlans} from './plan_js.mjs';
import {qdecls} from './shiki_q.mjs';
import {compileShiki} from './shiki_compile.mjs';

const [out, ...pairs] = process.argv.slice(2);
if (!out || !pairs.length) {
  console.error('usage: emit_shiki_rom.mjs OUT.c APP=FILE.js [APP=FILE.js ...]');
  process.exit(2);
}
const rows = [], arrays = [], seen = new Set();
for (const pair of pairs) {
  const at = pair.indexOf('=');
  const app = pair.slice(0, at), file = pair.slice(at + 1);
  const text = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'), q = qdecls(text);
  for (const plan of findPlans(text, file, ['shiki'])) {
    const name = `${app}.${plan.name}`;
    if (seen.has(name)) throw new Error(`${file}: ${name}: named twice`);
    seen.add(name);
    let c;
    try { c = compileShiki(plan, q.get(plan.name) ?? {}); }
    catch (e) { throw new Error(`${file}: @shiki ${plan.name}: ${e.message}`); }
    const v = `P${arrays.length}`;
    const bytes = Array.from(c.bytes);
    const lines = [];
    for (let i = 0; i < bytes.length; i += 16) lines.push('    ' + bytes.slice(i, i + 16).join(',') + ',');
    arrays.push(`/* ${name}: ${c.count} instructions */\nstatic const uint8_t ${v}[${bytes.length}] = {\n${lines.join('\n')}\n};`);
    rows.push(`    {"${name}", ${v}, ${bytes.length}},`);
    console.log(`${name}: ${c.count} instructions, ${bytes.length} B`);
  }
}
const text = [
  '/* Generated by tools/kasane_ir/emit_shiki_rom.mjs -- do not edit. From:',
  ...pairs.map(p => ` *   ${p}`),
  ' */',
  '#include "ksn_shiki.h"',
  '',
  ...arrays,
  '',
  `static const ksn_shiki_rom_entry ROM[${Math.max(1, rows.length)}] = {`,
  ...(rows.length ? rows : ['    {0},']),
  '};',
  'const ksn_shiki_rom_entry *ksn_shiki_rom_table(unsigned *count) {',
  `    *count = ${rows.length};`,
  '    return ROM;',
  '}',
  ''].join('\n');
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) fs.writeFileSync(out, text);
