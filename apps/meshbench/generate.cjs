try{vm.runInNewContext(source,{pocket:{kasane:{},ayatsuri:{modelOpen(buffer){decoded=Buffer.from(buffer);throw stop;}}}});}
catch(error){if(error!==stop)throw error;}
if(!decoded||!decoded.equals(cold))throw Error('generated fixture decoder mismatch');
const output=path.join(__dirname,'mesh_bench.js');
if(process.argv.includes('--check')){if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==source)throw Error('stale mesh_bench.js');}
else fs.writeFileSync(output,source);
console.log(JSON.stringify({bytes:cold.length,sha256:hash,meshes:4,triangles:8,sourceBytes:Buffer.byteLength(source)}));
